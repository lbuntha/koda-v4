/** Shown first: where Koda's families are. */
export const NEAR_COUNTRIES: readonly string[] = ["KH", "TH", "VN", "LA"];

const names = new Map<string, Intl.DisplayNames | null>();

/** A country's name in this language, or the code when the browser has no names. */
export const countryName = (code: string, lang: string): string => {
  if (!names.has(lang)) {
    try {
      names.set(lang, new Intl.DisplayNames([lang, "en"], { type: "region" }));
    } catch {
      names.set(lang, null);
    }
  }
  try {
    return names.get(lang)?.of(code) ?? code;
  } catch {
    return code;
  }
};

/** The likely country of this device, from its time zone, then its language. Null when unsure. */
export const guessCountry = (): string | null => {
  try {
    const zone = Intl.DateTimeFormat().resolvedOptions().timeZone ?? "";
    const byZone: Record<string, string> = {
      "Asia/Phnom_Penh": "KH",
      "Asia/Bangkok": "TH",
      "Asia/Ho_Chi_Minh": "VN",
      "Asia/Saigon": "VN",
      "Asia/Vientiane": "LA",
    };
    if (byZone[zone]) return byZone[zone];
    const region = (navigator.language || "").split("-")[1]?.toUpperCase();
    return region && COUNTRY_CODES.includes(region) ? region : null;
  } catch {
    return null;
  }
};

/** Countries whose name (in this language, English or Khmer) or code starts a word with the query. */
export const searchCountries = (query: string, lang: string): string[] => {
  const q = query.trim().toLocaleLowerCase();
  const all = [...NEAR_COUNTRIES, ...COUNTRY_CODES.filter((c) => !NEAR_COUNTRIES.includes(c))];
  if (!q) return all;
  const hit = (name: string) =>
    name
      .toLocaleLowerCase()
      .split(/[\s(),-]+/)
      .some((w) => w.startsWith(q)) || name.toLocaleLowerCase().startsWith(q);
  return all.filter((c) => c.toLowerCase() === q || hit(countryName(c, lang)) || hit(countryName(c, "en")) || hit(countryName(c, "km")));
};
